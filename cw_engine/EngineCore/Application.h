#ifndef ENGINE_APPLICATION_H
#define ENGINE_APPLICATION_H

#pragma once
#include <memory>
#include "Window.h"

namespace Engine {
    /**
     * @class Application
     * @brief Фундаментальний клас, що представляє всю програму.
     *
     * Цей клас є серцем рушія. Він відповідає за створення вікна,
     * запуск основного ігрового циклу (Game Loop) та виклик методів
     * оновлення та рендерингу на кожному кадрі.
     *
     * Щоб створити власну гру, вам потрібно успадкувати цей клас
     * та реалізувати його чисто віртуальні методи.
     */
    class Application {
    public:
        /**
         * @brief Конструктор. Створює вікно та ініціалізує ресурси.
         */
        Application();

        /**
         * @brief Віртуальний деструктор. Гарантує правильне звільнення ресурсів
         *        в дочірніх класах.
         */
        virtual ~Application();

        /**
         * @brief Запускає основний ігровий цикл.
         *
         * Цей метод буде працювати безкінечно (до закриття вікна),
         * на кожній ітерації вираховуючи час кадру (deltaTime) та викликаючи
         * OnUpdate() та OnRender().
         */
        void Run();

        /**
         * @brief Метод для оновлення логіки гри. Викликається на кожному кадрі.
         * @param deltaTime Час, що минув з попереднього кадру (в секундах).
         *                  Використовується для створення плавної, незалежної від FPS анімації та фізики.
         *
         * Це чисто віртуальний метод, який необхідно реалізувати в дочірньому класі.
         * Саме тут повинна відбуватися вся ігрова логіка: рух персонажів,
         * перевірка вводу, оновлення стану гри тощо.
         */
        virtual void OnUpdate(float deltaTime) = 0;

        /**
         * @brief Метод для рендерингу (малювання) сцени. Викликається на кожному кадрі.
         *
         * Це чисто віртуальний метод, який необхідно реалізувати в дочірньому класі.
         * Вся графіка повинна малюватися тут.
         */
        virtual void OnRender() = 0;

    private:
        std::unique_ptr<Window> m_Window; ///< Розумний вказівник на об'єкт вікна.
        bool m_Running = true;            ///< Прапорець, що контролює роботу ігрового циклу.
        float m_LastFrameTime = 0.0f;     ///< Час попереднього кадру для розрахунку deltaTime.
    };

    /**
     * @brief Функція, що створює екземпляр програми.
     * @return Вказівник на об'єкт вашої гри (дочірній клас Application).
     *
     * Ця функція повинна бути реалізована на стороні клієнта (у вашому проєкті cw_game).
     * Вона викликається з EntryPoint.h для запуску гри.
     */
    Application *CreateApplication();
}

#endif // ENGINE_APPLICATION_H
